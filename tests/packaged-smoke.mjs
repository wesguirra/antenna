// Run the signed executable itself: development Electron cannot catch dyld's
// signed-app library restrictions. Uses an isolated profile and local media.
import { spawn } from 'node:child_process';
import { mkdtempSync, writeFileSync, createReadStream, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { createServer } from 'node:net';
import { createServer as createHTTPServer } from 'node:http';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
const appPath = resolve(process.env.ANTENNA_TEST_APP || 'release/mac-arm64/Antenna.app');
const video = resolve(process.env.ANTENNA_SMOKE_VIDEO || '../work/sample.mp4');
const output = resolve(process.env.ANTENNA_SMOKE_OUTPUT || '../work');
const profile = mkdtempSync(join(tmpdir(), 'antenna-signed-smoke-'));
const server = createServer();
await new Promise(r => server.listen(0, "127.0.0.1", r));
const port = server.address().port;
await new Promise(r => server.close(r));
const child = spawn(join(appPath, 'Contents/MacOS/Antenna'), [`--user-data-dir=${profile}`, `--remote-debugging-port=${port}`, '--remote-debugging-address=127.0.0.1'], {stdio:['ignore','ignore','pipe']});
let launchOutput='';
child.stderr.on('data',data=>{launchOutput=(launchOutput+String(data)).slice(-16000);});
const delay = ms => new Promise(r=>setTimeout(r,ms));
const size=statSync(video).size;
const videoServer=createHTTPServer((req,res)=>{
  const range=/^bytes=(\d+)-(\d*)$/.exec(req.headers.range || '');
  const start=range ? Number(range[1]) : 0;
  const end=range?.[2] ? Math.min(Number(range[2]),size-1) : size-1;
  if(start>=size || end<start){res.writeHead(416,{'Content-Range':`bytes */${size}`});return res.end();}
  const headers={'Content-Type':'video/mp4','Content-Length':end-start+1,'Accept-Ranges':'bytes'};
  if(range)headers['Content-Range']=`bytes ${start}-${end}/${size}`;
  res.writeHead(range?206:200,headers);
  createReadStream(video,{start,end}).pipe(res);
});
await new Promise(r=>videoServer.listen(0,'127.0.0.1',r));
const episodeURL=n=>`http://127.0.0.1:${videoServer.address().port}/${n}.mp4`;
let socket;
try {
  let target;
  for (let i=0;i<300;i++) {
    try { target=(await (await fetch(`http://127.0.0.1:${port}/json/list`)).json()).find(t=>t.type==='page'); } catch {}
    if(target) break;
    await delay(100);
  }
  assert.ok(target, `signed app must launch (exit ${child.exitCode}): ${launchOutput}`);
  socket = new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((r,j)=>{socket.onopen=r;socket.onerror=j;});
  let seq=0;
  const pending=new Map();
  socket.onmessage=({data})=>{const msg=JSON.parse(data);if(msg.id){const p=pending.get(msg.id);pending.delete(msg.id);msg.error?p.reject(new Error(msg.error.message)):p.resolve(msg.result);}};
  const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++seq;pending.set(id,{resolve,reject});socket.send(JSON.stringify({id,method,params}));});
  const js=async expression=>{
    const result=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});
    if(result.exceptionDetails) throw new Error(result.exceptionDetails.exception?.description || result.exceptionDetails.text);
    return result.result.value;
  };
  await delay(700);
  assert.equal(await js('window.electron.playbackBackend'),'embedded');
  const poster='data:image/svg+xml;base64,'+Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="800" height="450"><rect width="800" height="450" fill="#354354"/></svg>').toString('base64');
  const cache={baseUrl:'https://example.invalid',username:'fixture',cachedAt:Date.now(),channels:[],groups:[],movies:[{id:1,streamId:1,name:'Horizonte',url:pathToFileURL(video).href,poster,backdrop:poster,rating:8,group:'Cinema'}],movieGroups:['Cinema'],series:[{id:1,seriesId:1,name:'Série de teste',poster,group:'Séries',episodes:[{name:'Primeiro encontro',season:1,episodeNum:1,url:episodeURL(1),poster:'https://127.0.0.1:1/unavailable.jpg'},{name:'Segundo encontro',season:1,episodeNum:2,url:episodeURL(2),poster},{name:'Uma nova temporada',season:2,episodeNum:1,url:episodeURL(3),poster}]}],seriesGroups:['Séries']};
  await js(`localStorage.setItem('livebox_xtreamCreds',${JSON.stringify(JSON.stringify({baseUrl:cache.baseUrl,username:'fixture',password:'fixture'}))});localStorage.setItem('livebox_xtreamCache',${JSON.stringify(JSON.stringify(cache))});location.reload()`);
  await delay(1800);
  await js(`document.querySelector('.topnav-link:nth-child(4)').click()`);
  await delay(350);
  await js(`document.querySelector('.series-browse .poster-card').click()`);
  await delay(800);
  await js(`document.querySelector('.episode-row')?.scrollIntoView()`);
  await delay(700);
  assert.equal(await js(`document.querySelector('.episode-thumb')?.src`),poster,'failed episode image must use series fallback');
  assert.equal(await js(`document.querySelector('.episode-thumb').naturalWidth > 0`),true);
  await js(`document.querySelector('.topnav-link:nth-child(1)').click()`);
  await delay(300);
  await js(`window.__times=[];window.electron.mpv.onEvent(e=>{if(e.type==='time')window.__times.push(e.value)});document.querySelector('.billboard .btn-primary').click()`);
  for(let i=0;i<100 && !(await js('window.__times.some(t=>t>1)'));i++) await delay(100);
  assert.ok(await js('window.__times.some(t=>t>1)'), 'signed native playback must advance');
  await js(`window.electron.mpv.command('pause',true)`);
  await delay(500);
  assert.ok(await js(`!!document.querySelector('[aria-label="Avançar 10 segundos"]')`));
  assert.equal(await js(`getComputedStyle(document.querySelector('.mpv-dock')).position`),'absolute');
  assert.equal(await js(`getComputedStyle(document.querySelector('.player-window-chrome')).webkitAppRegion`),'drag','windowed player has a persistent drag region');
  const videoHeight=await js(`document.querySelector('.mpv-surface').getBoundingClientRect().height`);
  assert.equal(videoHeight,await js('innerHeight'),'controls must not consume video height');
  await delay(3500);
  assert.equal(await js(`document.querySelector('.player-mpv').classList.contains('controls-hidden')`),true,'paused playback must also hide idle controls');
  assert.equal(await js(`getComputedStyle(document.querySelector('.mpv-dock')).opacity`),'0');
  assert.equal(await js(`document.querySelector('.mpv-surface').getBoundingClientRect().height`),videoHeight);
  await call('Input.dispatchMouseEvent',{type:'mouseMoved',x:100,y:100});await delay(250);
  assert.equal(await js(`getComputedStyle(document.querySelector('.mpv-dock')).opacity`),'1');
  const screenshot=await call('Page.captureScreenshot',{format:'png'});
  writeFileSync(join(output,'antenna-player-controls.png'),Buffer.from(screenshot.data,'base64'));
  await js(`document.querySelector('[aria-label="Avançar 10 segundos"]').click()`);
  await delay(800);
  assert.ok(await js('window.__times.at(-1)>=10'), 'skip control must seek');
  await js(`window.electron.mpv.command('seek',0)`);await delay(16000);
  assert.equal(await js(`!!document.querySelector('.mpv-surface')`),true,'pausing at zero must not trip the startup watchdog');
  const framesBeforePip=await js('window.electron.mpv.renderStatus()');
  await js('window.electron.pip.set(true)');await delay(500);
  const framesInPip=await js('window.electron.mpv.renderStatus()');
  assert.ok(framesInPip.frames > framesBeforePip.frames,'paused PiP must redraw the retained native video frame');
  assert.equal(framesInPip.width,await js('innerWidth * devicePixelRatio'));
  assert.equal(framesInPip.height,await js('innerHeight * devicePixelRatio'));
  assert.equal(await js('document.body.classList.contains("pip-active")'),true);
  assert.equal(await js(`!!document.querySelector('.player-window-chrome')`),false,'PiP has no normal window header');
  assert.equal(await js(`document.querySelector('.mpv-surface').getBoundingClientRect().top`),0);
  assert.equal(await js(`document.querySelector('.mpv-surface').getBoundingClientRect().height`),await js('innerHeight'));
  assert.equal(await js(`getComputedStyle(document.body,'::before').display`),'none');
  assert.equal(await js(`[...document.querySelectorAll('.mpv-dock button')].filter(b=>b.getClientRects().length>0).length`),3,'PiP has only close, pause and return');
  await delay(3500);
  assert.equal(await js(`getComputedStyle(document.querySelector('.mpv-dock')).opacity`),'0','PiP must hide idle controls');
  await call('Input.dispatchMouseEvent',{type:'mouseMoved',x:100,y:100});await delay(250);
  assert.equal(await js(`getComputedStyle(document.querySelector('.mpv-dock')).opacity`),'1');
  await js('window.electron.pip.set(false)');await delay(500);
  assert.equal(await js('document.body.classList.contains("pip-active")'),false);
  await js('window.electron.toggleFullscreen()');
  await delay(1200);
  assert.equal(await js('window.electron.isFullscreen()'),true,'transparent playback window supports OS fullscreen');
  assert.equal(await js(`!!document.querySelector('.player-window-chrome')`),false,'OS fullscreen has no draggable header');
  assert.equal(await js(`document.querySelector('.mpv-surface').getBoundingClientRect().height`),await js('innerHeight'));
  await js('window.electron.toggleFullscreen()');await delay(1200);
  assert.equal(await js('window.electron.isFullscreen()'),false);
  assert.equal(await js(`getComputedStyle(document.querySelector('.player-window-chrome')).webkitAppRegion`),'drag','drag region returns after fullscreen');
  await js(`document.querySelector('.mpv-back').click();document.querySelector('.topnav-link:nth-child(4)').click()`);
  await delay(350);
  await js(`document.querySelector('.series-detail .episode-row').click()`);
  await delay(1000);
  const widthBefore=await js(`document.querySelector('.mpv-surface').getBoundingClientRect().width`);
  await call('Input.dispatchMouseEvent',{type:'mouseMoved',x:100,y:100});await delay(100);
  await js(`document.querySelector('.mpv-episodes-toggle').focus()`);
  await call('Input.dispatchKeyEvent', {type:'keyDown', key:' ', code:'Space', windowsVirtualKeyCode:32});
  await call('Input.dispatchKeyEvent', {type:'keyUp', key:' ', code:'Space', windowsVirtualKeyCode:32});
  await delay(300);
  assert.equal(await js(`document.querySelector('.mpv-episodes-toggle').getAttribute('aria-expanded')`),'true');
  assert.equal(await js(`document.querySelectorAll('.mpv-episodes-panel .ep-sidebar-item').length`),2);
  assert.ok(await js(`document.querySelector('.mpv-surface').getBoundingClientRect().width`) < widthBefore, 'episode panel must leave the native video unobstructed');
  await js(`const s=document.querySelector('.mpv-episodes-panel select');s.value='2';s.dispatchEvent(new Event('change',{bubbles:true}))`);
  await delay(200);
  assert.equal(await js(`document.querySelectorAll('.mpv-episodes-panel .ep-sidebar-item').length`),1);
  await js(`document.querySelector('.mpv-episodes-panel .ep-sidebar-item').click()`);
  await delay(1000);
  assert.equal(await js(`document.querySelector('.mpv-now-episode').textContent`),'Uma nova temporada');
  assert.equal(await js(`!!document.querySelector('.mpv-episodes-panel')`),false);
  await js(`document.querySelector('.mpv-episodes-toggle').click()`);await delay(200);
  assert.equal(await js(`document.querySelector('.mpv-episodes-panel select').value`),'2');
  assert.equal(await js(`document.querySelector('.mpv-episodes-panel [aria-current="true"]').textContent.includes('Uma nova temporada')`),true);
  await js(`document.querySelector('button[title="Legendas"]').click()`);await delay(200);
  assert.equal(await js(`!!document.querySelector('.mpv-episodes-panel')`),false);
  await js(`document.querySelector('.mpv-episodes-toggle').click()`);await delay(200);
  assert.equal(await js(`!!document.querySelector('.online-subtitles')`),false);
  await js(`window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`);await delay(200);
  assert.equal(await js(`!!document.querySelector('.mpv-episodes-panel')`),false);
  assert.equal(await js(`!!document.querySelector('.mpv-surface')`),true);
  await js(`document.querySelector('.mpv-episodes-toggle').click()`);await delay(100);
  await js('window.electron.pip.set(true)');await delay(400);
  assert.equal(await js(`!!document.querySelector('.mpv-panel')`),false,'PiP clears nonessential open menus');
  await js('window.electron.pip.set(false)');await delay(300);
  console.log('PASS: signed native playback, seeking, PiP, artwork fallback, episode menu, season selection, episode switching, overlay bounds, idle controls in paused playback/PiP, OS fullscreen and Escape.');
} finally {
  socket?.close();
  child.kill('SIGTERM');
  await delay(700);
  videoServer.closeAllConnections();
  await new Promise(r=>videoServer.close(r));
}
